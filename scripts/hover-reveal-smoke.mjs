import { chromium } from 'playwright';
import assert from 'node:assert/strict';
const browser = await chromium.launch();
const base = process.env.TEST_URL || 'http://localhost:5173';
const page = await browser.newPage({ viewport: { width: 1200, height: 850 } });
const errors = [];
page.on('pageerror', error => errors.push(error.message));
try {
  await page.goto(`${base}/preview/hover-reveal?embed=1&drift=false`, { waitUntil: 'networkidle' });
  const images = page.locator('.hover-reveal__image');
  const active = () => page.locator('.hover-reveal__list button[aria-current=true]');
  assert.equal(await images.count(), 5);
  assert.equal(await active().getAttribute('aria-label'), '01 Blackframe');
  await page.getByRole('button', { name: '02 Novagrid', exact: true }).hover();
  await page.waitForTimeout(100);
  const midway = await images.nth(1).evaluate(el => ({ opacity: Number(getComputedStyle(el).opacity), scale: new DOMMatrix(getComputedStyle(el).transform).a }));
  assert.ok(midway.opacity > 0 && midway.opacity < 1, 'image should crossfade');
  assert.ok(midway.scale > 1 && midway.scale < 1.4, 'incoming image should settle from 1.4x');
  await page.waitForFunction(() => getComputedStyle(document.querySelectorAll('.hover-reveal__image')[1]).opacity === '1');
  assert.equal(await active().getAttribute('aria-label'), '02 Novagrid');
  for (const label of ['05 Obsedian', '04 Phantom', '03 Ather']) await page.getByRole('button', { name: label, exact: true }).hover();
  await page.waitForTimeout(1500);
  const opacities = await images.evaluateAll(els => els.map(el => Number(getComputedStyle(el).opacity)));
  assert.deepEqual(opacities, [0, 0, 1, 0, 0], 'rapid changes should leave one correct image');
  await page.mouse.move(1, 1);
  assert.equal(await active().getAttribute('aria-label'), '03 Ather', 'selection persists on leave');
  await page.getByRole('button', { name: '03 Ather', exact: true }).focus();
  await page.keyboard.press('ArrowDown');
  assert.equal(await active().getAttribute('aria-label'), '04 Phantom');
  await page.keyboard.press('Home');
  assert.equal(await active().getAttribute('aria-label'), '01 Blackframe');
  await page.keyboard.press('End');
  assert.equal(await active().getAttribute('aria-label'), '05 Obsedian');
  await page.keyboard.press('ArrowRight');
  assert.equal(await active().getAttribute('aria-label'), '01 Blackframe');
  const box = await page.locator('.hover-reveal').boundingBox();
  await page.mouse.move(box.x + 2, box.y + box.height / 2);
  await page.waitForTimeout(1000);
  const translate = await page.locator('.hover-reveal__motion').evaluate(el => new DOMMatrix(getComputedStyle(el).transform).m41);
  assert.ok(translate < -8 && translate >= -9, 'parallax should use the full container bounds');
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.reload({ waitUntil: 'networkidle' });
  await page.getByRole('button', { name: '04 Phantom', exact: true }).hover();
  assert.equal(await images.nth(3).evaluate(el => getComputedStyle(el).opacity), '1');
  assert.equal(await images.nth(3).evaluate(el => el.getAnimations().length), 0);
  assert.equal(await page.locator('.hover-reveal__motion').evaluate(el => getComputedStyle(el).transform), 'none');
  await page.emulateMedia({ reducedMotion: 'no-preference' });
  await page.goto(`${base}/components/hover-reveal`, { waitUntil: 'networkidle' });
  await page.getByRole('heading', { name: 'Hover Reveal', exact: true }).waitFor();
  await page.getByRole('button', { name: 'Customize', exact: true }).click();
  await page.getByLabel('Index label', { exact: true }).fill('Our team');
  await page.getByLabel('Panel theme', { exact: true }).selectOption('light');
  await page.getByLabel(/Crossfade duration/).fill('500');
  await page.getByRole('switch', { name: 'Idle image drift', exact: true }).click();
  await page.frameLocator('iframe').locator('.hover-reveal[data-theme=light]').waitFor();
  await page.getByRole('tab', { name: 'Usage', exact: true }).click();
  const usage = await page.locator('#playground-panel pre').innerText();
  assert.ok(usage.includes('Our team') && usage.includes('duration={500}') && usage.includes('drift={false}') && usage.includes('theme="light"'));
  await page.getByRole('tab', { name: 'Component', exact: true }).click();
  assert.ok((await page.locator('#playground-panel pre').innerText()).includes('function HoverReveal'));
  await page.locator('#playground-panel .ms-copy').click();
  await page.locator('#playground-panel').getByRole('button', { name: 'Copied', exact: true }).waitFor();
  await page.getByRole('tab', { name: 'CSS', exact: true }).click();
  assert.ok((await page.locator('#playground-panel pre').innerText()).includes('@container hover-reveal'));
  const download = page.waitForEvent('download');
  await page.getByRole('link', { name: 'Download files', exact: true }).click();
  assert.equal((await download).suggestedFilename(), 'hover-reveal.zip');
  await page.getByRole('button', { name: 'Reset', exact: true }).click();
  assert.equal(await page.getByLabel('Index label', { exact: true }).inputValue(), 'Protocols');
  await page.getByRole('tab', { name: 'Preview', exact: true }).click();
  await page.getByRole('button', { name: 'Mobile preview', exact: true }).click();
  await page.frameLocator('iframe').locator('.hover-reveal__index').waitFor();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.waitForTimeout(300);
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  const touch = await browser.newPage({ viewport: { width: 390, height: 844 }, hasTouch: true, isMobile: true });
  await touch.goto(`${base}/preview/hover-reveal?embed=1`, { waitUntil: 'networkidle' });
  const layout = await touch.locator('.hover-reveal__layout').evaluate(el => getComputedStyle(el).gridTemplateColumns);
  assert.ok(!layout.includes(' '), 'mobile layout should have one column');
  await touch.getByRole('button', { name: '05 Obsedian', exact: true }).tap();
  assert.equal(await touch.locator('button[aria-current=true]').getAttribute('aria-label'), '05 Obsedian');
  await touch.close();
  const fallback = await browser.newPage();
  await fallback.route('**/hover-reveal/ather.webp', route => route.abort());
  await fallback.goto(`${base}/preview/hover-reveal?embed=1`, { waitUntil: 'networkidle' });
  await fallback.getByRole('button', { name: '03 Ather', exact: true }).click();
  await fallback.getByText('Image unavailable', { exact: true }).waitFor();
  await fallback.getByRole('button', { name: '02 Novagrid', exact: true }).click();
  await fallback.locator('.hover-reveal__unavailable').waitFor({ state: 'hidden' });
  await fallback.close();
  assert.deepEqual(errors, []);
  console.log('PASS: Hover Reveal crossfade/zoom, rapid hover, persistent selection, keyboard, pointer range, reduced motion, playground configuration, source tabs/copy, ZIP, mobile/touch, and failed-image recovery.');
} finally { await browser.close(); }
