import { chromium } from 'playwright';
import assert from 'node:assert/strict';
const browser = await chromium.launch();
const base = process.env.TEST_URL || 'http://localhost:5173';
const page = await browser.newPage({ viewport: { width: 1200, height: 850 } });
const errors = [];
page.on('pageerror', error => errors.push(error.message));
const closed = () => page.locator('dialog').waitFor({ state: 'detached' });
try {
  await page.goto(`${base}/preview/bento-grid?embed=1`, { waitUntil: 'networkidle' });
  assert.equal(await page.locator('.bento-grid__tile').count(), 6);
  assert.deepEqual(await page.locator('.bento-grid').boundingBox(), { x: 88, y: 83, width: 1024, height: 684 });
  const lead = page.getByRole('button', { name: 'Neon run', exact: true });
  await lead.hover(); await page.waitForTimeout(350);
  assert.ok(Math.abs(await lead.locator('img').evaluate(el => new DOMMatrix(getComputedStyle(el).transform).a) - 1.04) < .001);
  await lead.click();
  await page.waitForTimeout(120);
  const midway = await page.locator('.bento-grid__expanded').boundingBox();
  assert.ok(midway.width > 506 && midway.width < 752, 'image should expand from its tile');
  await page.waitForTimeout(750);
  assert.deepEqual(await page.locator('.bento-grid__expanded').boundingBox(), { x: 24, y: 24, width: 752, height: 802 });
  assert.equal(await page.getByRole('button', { name: 'Previous', exact: true }).isDisabled(), true);
  assert.equal(await page.evaluate(() => document.body.style.overflow), 'hidden');
  await page.getByRole('link', { name: 'Li Zhang', exact: true }).focus();
  await page.keyboard.press('Tab');
  assert.equal(await page.evaluate(() => document.activeElement.getAttribute('aria-label')), 'Next');
  await page.keyboard.press('Shift+Tab');
  assert.equal(await page.evaluate(() => document.activeElement.textContent), 'Li Zhang');
  await page.keyboard.press('ArrowRight');
  await page.getByRole('heading', { name: 'Low and wide', exact: true }).waitFor();
  await page.getByRole('button', { name: 'Close', exact: true }).click(); await closed();
  await page.waitForFunction(() => document.activeElement.getAttribute('aria-label') === 'Low and wide');
  assert.notEqual(await page.evaluate(() => document.body.style.overflow), 'hidden');
  await page.keyboard.press('Enter');
  await page.getByRole('dialog').waitFor();
  for (let i = 0; i < 8; i++) await page.keyboard.press('ArrowRight');
  await page.getByRole('heading', { name: 'Last stop', exact: true }).waitFor();
  assert.equal(await page.getByRole('button', { name: 'Next', exact: true }).isDisabled(), true);
  await page.keyboard.press('Escape'); await closed();
  await lead.click();
  await page.waitForTimeout(850);
  await page.mouse.click(5, 5); await closed();
  // Resize an open modal; its destination and subsequent return must stay valid.
  await lead.click();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.waitForTimeout(400);
  assert.deepEqual(await page.locator('.bento-grid__expanded').boundingBox(), { x: 12, y: 12, width: 366, height: 388 });
  assert.deepEqual(await page.locator('.bento-grid__panel').boundingBox(), { x: 0, y: 412, width: 390, height: 432 });
  await page.screenshot({ path: 'test-artifacts/bento-grid/ours-mobile-open.png' });
  await page.keyboard.press('Escape'); await closed();
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  assert.equal(await page.locator('.bento-grid__tile').first().evaluate(el => el.clientHeight), 312);
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.reload({ waitUntil: 'networkidle' });
  await lead.click();
  assert.equal(await page.getByRole('dialog').evaluate(el => el.getAnimations({ subtree: true }).length), 0);
  await page.keyboard.press('Escape'); await closed();
  await page.emulateMedia({ reducedMotion: 'no-preference' });
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.goto(`${base}/components/bento-grid`, { waitUntil: 'networkidle' });
  await page.getByRole('heading', { name: 'Bento Grid', exact: true }).waitFor();
  await page.screenshot({ path: 'test-artifacts/bento-grid/docs.png' });
  await page.getByRole('button', { name: 'Customize', exact: true }).click();
  await page.getByLabel('Columns', { exact: true }).fill('3');
  await page.getByLabel('Grid gap', { exact: true }).fill('20');
  await page.getByLabel('Panel theme', { exact: true }).selectOption('light');
  await page.frameLocator('iframe').locator('.bento-grid[data-theme=light]').waitFor();
  await page.frameLocator('iframe').getByRole('button', { name: 'Neon run', exact: true }).click();
  await page.frameLocator('iframe').locator('dialog[data-theme=light]').waitFor();
  await page.frameLocator('iframe').getByRole('button', { name: 'Close', exact: true }).click();
  await page.getByRole('tab', { name: 'Usage', exact: true }).click();
  const usage = await page.locator('#playground-panel pre').innerText();
  assert.ok(usage.includes('columns={3}') && usage.includes('gap={20}') && usage.includes('theme="light"'));
  await page.getByRole('tab', { name: 'Component', exact: true }).click();
  assert.ok((await page.locator('#playground-panel pre').innerText()).includes('function BentoGrid'));
  await page.locator('#playground-panel .ms-copy').click();
  await page.locator('#playground-panel').getByRole('button', { name: 'Copied', exact: true }).waitFor();
  await page.getByRole('tab', { name: 'CSS', exact: true }).click();
  assert.ok((await page.locator('#playground-panel pre').innerText()).includes('.bento-grid__dialog'));
  const download = page.waitForEvent('download'); await page.getByRole('link', { name: 'Download files', exact: true }).click();
  assert.equal((await download).suggestedFilename(), 'bento-grid.zip');
  await page.getByRole('button', { name: 'Reset', exact: true }).click();
  assert.equal(await page.getByLabel('Columns', { exact: true }).inputValue(), '4');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.waitForTimeout(250);
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  const touch = await browser.newPage({ viewport: { width: 390, height: 844 }, hasTouch: true, isMobile: true });
  await touch.goto(`${base}/preview/bento-grid?embed=1`, { waitUntil: 'networkidle' });
  await touch.getByRole('button', { name: 'Neon run', exact: true }).tap();
  await touch.getByRole('heading', { name: 'Neon run', exact: true }).waitFor();
  await touch.getByRole('button', { name: 'Next', exact: true }).tap();
  await touch.getByRole('heading', { name: 'Low and wide', exact: true }).waitFor();
  await touch.getByRole('button', { name: 'Close', exact: true }).tap();
  await touch.locator('dialog').waitFor({ state: 'detached' }); await touch.close();
  const fallback = await browser.newPage();
  await fallback.route('**/bento-grid/neon.webp', route => route.abort());
  await fallback.goto(`${base}/preview/bento-grid?embed=1`, { waitUntil: 'networkidle' });
  await fallback.locator('.bento-grid__fallback').waitFor();
  await fallback.getByRole('button', { name: 'Neon run', exact: true }).click();
  await fallback.locator('dialog .bento-grid__fallback').waitFor();
  await fallback.getByRole('button', { name: 'Next', exact: true }).click();
  await fallback.locator('dialog .bento-grid__fallback').waitFor({ state: 'hidden' });
  await fallback.close();
  assert.deepEqual(errors, []);
  console.log('PASS: Bento layout, hover zoom, tile expansion, modal bounds, focus trap/restore, arrows/endpoints, Escape/backdrop dismissal, scroll lock, responsive resize, reduced motion, configuration, source/copy/download, mobile touch and image failure recovery.');
} finally { await browser.close(); }
