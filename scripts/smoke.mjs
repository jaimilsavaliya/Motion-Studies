import {readFileSync} from 'node:fs';
const componentCount=[...readFileSync('src/library/registry.js','utf8').matchAll(/slug: '([^']+)'/g)].length;
import { chromium } from 'playwright';
import assert from 'node:assert/strict';
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
const errors = [];
page.on('pageerror', error => errors.push(error.message));
const base = process.env.TEST_URL || 'http://localhost:5173';
try {
  await page.goto(base, { waitUntil: 'networkidle' });
  await page.locator('.ms-catalog').waitFor();
  await page.getByRole('textbox', { name: 'Filter components' }).fill('no matches');
  await page.getByRole('heading', { name: 'No components found' }).waitFor();
  await page.getByRole('button', { name: 'Clear filters' }).click();
  assert.equal(await page.locator('.ms-component-card').count(), componentCount);
  await page.keyboard.press('Control+k');
  await page.getByRole('textbox', { name: 'Search components and documentation' }).fill('scroll');
  await page.keyboard.press('Enter');
  await page.locator('.ms-detail-heading').waitFor();
  await page.frameLocator('iframe').locator('.zoom-reveal__media').waitFor();
  const frame = page.frames().find(frame => frame.url().includes('/preview/'));
  const initialWidth = await frame.locator('.zoom-reveal__media').evaluate(el => el.clientWidth);
  await frame.evaluate(() => window.scrollTo(0, 2000));
  await frame.waitForFunction(() => document.querySelector('.zoom-reveal__media').clientWidth > 500);
  await page.getByRole('button', { name: 'Restart preview' }).click();
  await page.frameLocator('iframe').locator('.zoom-reveal__media').waitFor();
  assert.equal(initialWidth, 96);
  await page.getByRole('tab', { name: 'Component', exact: true }).click();
  await page.locator('#playground-panel .ms-copy').click();
  await page.locator('#playground-panel').getByRole('button', { name: 'Copied', exact: true }).waitFor();
  assert.ok((await page.locator('#playground-panel pre').innerText()).includes("'use client'"));
  await page.getByRole('tab', { name: 'CSS', exact: true }).click();
  assert.ok((await page.locator('#playground-panel pre').innerText()).includes('.zoom-reveal'));
  await page.getByRole('tab', { name: 'Preview', exact: true }).click();
  await page.getByRole('button', { name: 'Mobile preview', exact: true }).click();
  await page.getByRole('button', { name: 'Customize', exact: true }).click();
  await page.getByLabel('Leading text').fill('Beyond');
  await page.getByLabel('Media type').selectOption('image');
  await page.frameLocator('iframe').locator('img').waitFor();
  await page.getByRole('tab', { name: 'Usage', exact: true }).click();
  const usage = await page.locator('#playground-panel pre').innerText();
  assert.ok(usage.includes('Beyond') && usage.includes('<img'));
  const downloadPromise = page.waitForEvent('download');
  await page.getByRole('link', { name: 'Download files', exact: true }).click();
  assert.equal((await downloadPromise).suggestedFilename(), 'scroll-zoom-reveal.zip');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto(`${base}/components/scroll-zoom-reveal`, { waitUntil: 'networkidle' });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await page.getByRole('button', { name: 'Toggle navigation' }).click();
  await page.locator('.ms-sidebar').getByRole('link', { name: 'Installation', exact: true }).click();
  await page.locator('.ms-guide').waitFor();
  assert.equal(await page.locator('.ms-sidebar.open').count(), 0);
  await page.getByRole('button', { name: 'Switch to light theme' }).click();
  await page.waitForFunction(() => document.documentElement.dataset.theme === 'light');
  await page.reload({ waitUntil: 'networkidle' });
  assert.equal(await page.locator('html').getAttribute('data-theme'), 'light');
  await page.goto(`${base}/components/missing`);
  await page.getByRole('heading', { name: 'Nothing here. Yet.' }).waitFor();
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.goto(`${base}/preview/scroll-zoom-reveal`, { waitUntil: 'networkidle' });
  assert.equal(await page.locator('video').evaluate(video => video.paused), true);
  assert.deepEqual(errors, []);
  console.log('PASS: search, filters, routing, preview scroll, reset, source tabs, clipboard, customization, downloads, mobile layout/navigation, theme persistence, 404, reduced motion. No browser errors.');
} finally { await browser.close(); }
