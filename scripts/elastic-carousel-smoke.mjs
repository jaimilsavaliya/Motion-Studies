import {mkdirSync} from 'node:fs';
mkdirSync('test-artifacts/elastic-carousel',{recursive:true});
import { chromium } from 'playwright';
import assert from 'node:assert/strict';
const browser=await chromium.launch({args:['--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader']});
const base=process.env.TEST_URL||'http://localhost:5173';
const page=await browser.newPage({viewport:{width:1200,height:850}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
const stage=()=>page.locator('.elastic-carousel');
const selected=()=>page.locator('.elastic-carousel__card[aria-current=true]');
try{
  await page.goto(`${base}/preview/elastic-carousel?embed=1`,{waitUntil:'networkidle'});
  await page.waitForTimeout(4000);
  assert.equal(await stage().getAttribute('data-renderer'),'webgl');
  // Software rendering may need extra frames to finish the entrance; retain exact final geometry checks.
  await page.waitForFunction(()=>{const e=document.querySelector('.elastic-carousel__card[aria-current=true]');return e&&parseFloat(e.style.height)===336&&parseFloat(e.style.width)===224;});
  assert.deepEqual(await selected().boundingBox(),{x:488,y:257,width:224,height:336});
  assert.equal(await stage().getAttribute('data-index'),'3');
  await page.getByRole('button',{name:'View Kitesurfer',exact:true}).click();
  await page.waitForTimeout(900);
  assert.equal(await stage().getAttribute('data-open'),'true');
  // Wait for the physical fade to settle, rather than assuming a GPU/frame rate.
  await page.waitForFunction(()=>[...document.querySelectorAll('.elastic-carousel__card')].filter(e=>Number(getComputedStyle(e).opacity)>.01).length===1);
  const opacities=await page.locator('.elastic-carousel__card').evaluateAll(es=>es.map(e=>Number(getComputedStyle(e).opacity)));
  assert.equal(opacities.filter(v=>v>.01).length,1);
  await page.getByRole('button',{name:'Close',exact:true}).click();await page.waitForTimeout(850);
  assert.equal(await stage().getAttribute('data-open'),'false');
  await stage().focus();await page.keyboard.press('ArrowRight');await page.waitForTimeout(900);
  assert.equal(await stage().getAttribute('data-index'),'4');
  await page.keyboard.press('Enter');await page.waitForTimeout(700);assert.equal(await stage().getAttribute('data-open'),'true');
  await page.keyboard.press('Escape');assert.equal(await stage().getAttribute('data-open'),'false');
  await page.waitForTimeout(600);
  await page.mouse.move(600,425);await page.mouse.down();await page.mouse.move(350,425,{steps:12});
  const blur=await selected().evaluate(e=>parseFloat(e.style.getPropertyValue('--elastic-smear')));
  assert.ok(blur>0,'drag velocity should activate motion blur');
  await page.mouse.up();await page.waitForTimeout(1200);
  assert.equal(await stage().getAttribute('data-index'),'5');
  assert.deepEqual(await selected().boundingBox(),{x:488,y:257,width:224,height:336});
  await page.waitForFunction(()=>parseFloat(document.querySelector('.elastic-carousel__card[aria-current=true]').style.getPropertyValue('--elastic-smear'))===0);
  assert.equal(await selected().evaluate(e=>parseFloat(e.style.getPropertyValue('--elastic-smear'))),0);
  // Native context loss must preserve a usable gallery, and restoration must rebuild the renderer.
  await page.locator('canvas').evaluate(c=>{const ext=c.getContext('webgl').getExtension('WEBGL_lose_context');window.elasticContextTest=ext;ext.loseContext();});
  await page.locator('.elastic-carousel[data-renderer=fallback]').waitFor();
  await page.getByRole('button',{name:'Next image',exact:true}).click();await page.waitForTimeout(850);
  assert.equal(await stage().getAttribute('data-index'),'6');
  await page.evaluate(()=>window.elasticContextTest.restoreContext());
  await page.locator('.elastic-carousel[data-renderer=webgl]').waitFor();
  await page.emulateMedia({reducedMotion:'reduce'});await page.reload({waitUntil:'networkidle'});
  await page.getByRole('button',{name:'Next image',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('.elastic-carousel').dataset.index==='4');
  assert.equal(await selected().evaluate(e=>parseFloat(e.style.getPropertyValue('--elastic-smear'))),0);
  assert.equal(await selected().evaluate(e=>parseFloat(e.style.getPropertyValue('--elastic-skew'))),0);
  await page.emulateMedia({reducedMotion:'no-preference'});
  await page.goto(`${base}/components/elastic-carousel`,{waitUntil:'networkidle'});
  await page.getByRole('heading',{name:'Elastic Carousel',exact:true}).waitFor();
  await page.screenshot({path:'test-artifacts/elastic-carousel/docs.png'});
  await page.getByRole('button',{name:'Customize',exact:true}).click();
  await page.getByLabel('Stage height',{exact:true}).fill('520');
  await page.getByLabel('Elastic stretch',{exact:true}).fill('0.5');
  await page.getByLabel('Motion blur',{exact:true}).fill('0');
  await page.getByRole('switch',{name:'Thumbnail entrance',exact:true}).click();
  await page.waitForTimeout(500);
  await page.getByRole('tab',{name:'Usage',exact:true}).click();
  const usage=await page.locator('#playground-panel pre').innerText();
  assert.ok(usage.includes('height={520}')&&usage.includes('stretch={0.5}')&&usage.includes('blur={0}')&&usage.includes('intro={false}'));
  await page.getByRole('tab',{name:'Component',exact:true}).click();
  assert.ok((await page.locator('#playground-panel pre').innerText()).includes('function ElasticCarousel'));
  await page.locator('#playground-panel .ms-copy').click();await page.locator('#playground-panel').getByRole('button',{name:'Copied',exact:true}).waitFor();
  await page.getByRole('tab',{name:'CSS',exact:true}).click();assert.ok((await page.locator('#playground-panel pre').innerText()).includes('.elastic-carousel__canvas'));
  const download=page.waitForEvent('download');await page.getByRole('link',{name:'Download files',exact:true}).click();assert.equal((await download).suggestedFilename(),'elastic-carousel.zip');
  await page.getByRole('button',{name:'Reset',exact:true}).click();assert.equal(await page.getByLabel('Stage height',{exact:true}).inputValue(),'560');
  await page.setViewportSize({width:390,height:844});await page.waitForTimeout(250);assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
  const mobile=await browser.newPage({viewport:{width:390,height:844},hasTouch:true,isMobile:true});
  await mobile.goto(`${base}/preview/elastic-carousel?embed=1&intro=false`,{waitUntil:'networkidle'});
  assert.deepEqual(await mobile.locator('[aria-current=true]').boundingBox(),{x:119,y:321,width:152,height:202});
  await mobile.getByRole('button',{name:'View Kitesurfer',exact:true}).tap();await mobile.waitForTimeout(900);
  assert.equal(await mobile.locator('.elastic-carousel').getAttribute('data-open'),'true');
  await mobile.screenshot({path:'test-artifacts/elastic-carousel/ours-mobile.png'});
  await mobile.getByRole('button',{name:'Close',exact:true}).tap();await mobile.waitForTimeout(700);
  const cdp=await mobile.context().newCDPSession(mobile);
  await cdp.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[{x:260,y:420}]});
  for(let i=1;i<=12;i++)await cdp.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[{x:260-i*12,y:420}]});
  await cdp.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]});await mobile.waitForTimeout(1000);
  assert.equal(await mobile.locator('.elastic-carousel').getAttribute('data-index'),'4');await mobile.close();
  const fallback=await browser.newPage();
  await fallback.addInitScript(()=>{const original=HTMLCanvasElement.prototype.getContext;HTMLCanvasElement.prototype.getContext=function(type,...args){return type==='webgl'?null:original.call(this,type,...args);};});
  await fallback.goto(`${base}/preview/elastic-carousel?intro=false`,{waitUntil:'networkidle'});
  assert.equal(await fallback.locator('.elastic-carousel').getAttribute('data-renderer'),'fallback');
  await fallback.getByRole('button',{name:'Next image',exact:true}).click();await fallback.waitForTimeout(900);
  assert.equal(await fallback.locator('.elastic-carousel').getAttribute('data-index'),'4');await fallback.close();
  const failed=await browser.newPage();await failed.route('**/parallax-carousel/4.webp',r=>r.abort());
  await failed.goto(`${base}/preview/elastic-carousel?intro=false`,{waitUntil:'networkidle'});
  await failed.locator('[aria-current=true] .elastic-carousel__fallback').waitFor();await failed.close();
  assert.deepEqual(errors,[]);
  console.log('PASS: Elastic WebGL, reel/detail geometry, close/Escape, keyboard, drag/blur/snap, context loss/restoration, reduced motion, playground/source/copy/download, mobile tap/swipe, no-WebGL fallback and failed-image handling.');
}finally{await browser.close();}
