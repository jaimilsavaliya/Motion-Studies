import { chromium } from 'playwright';
import assert from 'node:assert/strict';
const browser = await chromium.launch();
const base = process.env.TEST_URL || 'http://localhost:5173';
const page = await browser.newPage({ viewport: { width: 1200, height: 850 } });
const errors = [];
page.on('pageerror', error => errors.push(error.message));
try {
  await page.goto(`${base}/preview/radial-pop-out?embed=1`, { waitUntil: 'networkidle' });
  const hero = page.getByRole('button', { name: 'Explore Japan', exact: true });
  assert.equal(await hero.getAttribute('aria-expanded'), 'false');
  assert.equal((await page.locator('.radial-pop-out__anchor').boundingBox()).width, 280);
  await hero.hover();
  await page.waitForTimeout(100);
  const delays = await page.locator('.radial-pop-out__card').evaluateAll(els => els.map(el => el.getAnimations()[0]?.effect.getTiming().delay));
  assert.deepEqual(delays, [0, 25, 50, 75, 100, 125, 150]);
  await page.waitForTimeout(1000);
  const geometry = await page.locator('.radial-pop-out__card').evaluateAll(els => els.map(el => {
    const m = new DOMMatrixReadOnly(getComputedStyle(el).transform);
    return { x: m.m41, y: m.m42, opacity: Number(getComputedStyle(el).opacity) };
  }));
  for (let i = 0; i < 7; i++) {
    const angle = -Math.PI / 2 + i * Math.PI * 2 / 7;
    assert.ok(Math.abs(geometry[i].x - Math.cos(angle) * 210) < 0.01);
    assert.ok(Math.abs(geometry[i].y - Math.sin(angle) * 210) < 0.01);
    assert.equal(geometry[i].opacity, 1);
  }
  await page.mouse.move(700, 500);
  await page.waitForTimeout(900);
  const transform = await hero.evaluate(el => new DOMMatrixReadOnly(getComputedStyle(el).transform));
  const translation = await hero.evaluate(el => { const m = new DOMMatrixReadOnly(getComputedStyle(el).transform); return [m.m41, m.m42]; });
  assert.ok(Math.abs(translation[0] - 36) < 0.3 && Math.abs(translation[1] - 27) < 0.3);
  await page.mouse.move(15, 15);
  await page.waitForTimeout(300);
  assert.equal(await hero.getAttribute('aria-expanded'), 'false');
  assert.ok((await page.locator('.radial-pop-out__card').evaluateAll(els => els.map(el => Number(getComputedStyle(el).opacity)))).every(value => value === 0));
  // Mid-flight reversal should not leave ghost cards or old animations behind.
  for (let i = 0; i < 3; i++) { await hero.hover(); await page.waitForTimeout(50); await page.mouse.move(15, 15); }
  await page.waitForTimeout(400);
  assert.equal(await page.locator('.radial-pop-out__card').evaluateAll(els => els.flatMap(el => el.getAnimations()).length), 0);
  await hero.focus();
  await page.waitForFunction(() => document.querySelector('.radial-pop-out__hero').getAttribute('aria-expanded') === 'true');
  await page.keyboard.press('Escape');
  assert.equal(await hero.getAttribute('aria-expanded'), 'false');
  await page.keyboard.press('Enter');
  await page.waitForFunction(() => document.querySelector('.radial-pop-out__hero').getAttribute('aria-expanded') === 'true');
  await page.keyboard.press('Space');
  await page.waitForFunction(() => document.querySelector('.radial-pop-out__hero').getAttribute('aria-expanded') === 'false');
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.reload({ waitUntil: 'networkidle' });
  await hero.hover();
  await page.waitForFunction(() => getComputedStyle(document.querySelector('.radial-pop-out__card')).opacity === '1');
  assert.equal(await page.locator('.radial-pop-out__card').evaluateAll(els => els.flatMap(el => el.getAnimations()).length), 0);
  assert.equal(await hero.evaluate(el => getComputedStyle(el).transform), 'none');
  await page.emulateMedia({ reducedMotion: 'no-preference' });
  await page.goto(`${base}/components/radial-pop-out`, { waitUntil: 'networkidle' });
  await page.getByRole('heading', { name: 'Radial Pop-out', exact: true }).waitFor();
  await page.getByRole('button', { name: 'Customize', exact: true }).click();
  await page.getByLabel('Satellite size', { exact: true }).fill('140');
  await page.getByLabel('Related images', { exact: true }).fill('4');
  await page.getByRole('switch', { name: 'Start expanded', exact: true }).click();
  await page.frameLocator('iframe').locator('.radial-pop-out[data-open=true]').waitFor();
  await page.getByRole('tab', { name: 'Usage', exact: true }).click();
  const usage = await page.locator('#playground-panel pre').innerText();
  assert.ok(usage.includes('cardSize={140}') && usage.includes('items.slice(0, 4)') && usage.includes('defaultOpen={true}'));
  await page.getByRole('tab', { name: 'Component', exact: true }).click();
  assert.ok((await page.locator('#playground-panel pre').innerText()).includes('function RadialPopOut'));
  await page.locator('#playground-panel .ms-copy').click();
  await page.locator('#playground-panel').getByRole('button', { name: 'Copied', exact: true }).waitFor();
  await page.getByRole('tab', { name: 'CSS', exact: true }).click();
  assert.ok((await page.locator('#playground-panel pre').innerText()).includes('.radial-pop-out__hero'));
  const download = page.waitForEvent('download');
  await page.getByRole('link', { name: 'Download files', exact: true }).click();
  assert.equal((await download).suggestedFilename(), 'radial-pop-out.zip');
  await page.getByRole('button', { name: 'Reset', exact: true }).click();
  assert.equal(await page.getByLabel('Satellite size', { exact: true }).inputValue(), '200');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.waitForTimeout(300);
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  const touch = await browser.newPage({ viewport: { width: 390, height: 844 }, hasTouch: true, isMobile: true });
  await touch.goto(`${base}/preview/radial-pop-out?embed=1`, { waitUntil: 'networkidle' });
  const touchHero = touch.getByRole('button', { name: 'Explore Japan', exact: true });
  assert.equal((await touch.locator('.radial-pop-out__anchor').boundingBox()).width, 150);
  await touchHero.tap();
  await touch.waitForFunction(() => document.querySelector('.radial-pop-out').dataset.open === 'true');
  await touch.waitForTimeout(1000);
  assert.equal(await touch.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  const bounds = await touch.locator('.radial-pop-out__card').evaluateAll(els => els.map(el => { const r = el.getBoundingClientRect(); return [r.left, r.right]; }));
  assert.ok(bounds.every(([left, right]) => left >= 0 && right <= 390));
  await touchHero.tap();
  await touch.waitForFunction(() => document.querySelector('.radial-pop-out').dataset.open === 'false');
  await touch.close();
  assert.deepEqual(errors, []);
  console.log('PASS: Radial geometry, stagger, magnetic tilt, hover exit/reversal, keyboard toggle/Escape, reduced motion, playground configuration, copy/download, reset, mobile scaling and touch.');
} finally { await browser.close(); }
