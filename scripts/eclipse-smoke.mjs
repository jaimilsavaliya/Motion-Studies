import {readFileSync} from 'node:fs';
const componentCount=[...readFileSync('src/library/registry.js','utf8').matchAll(/slug: '([^']+)'/g)].length;
import { chromium } from 'playwright';
import assert from 'node:assert/strict';
const browser = await chromium.launch({ args: ['--enable-webgl', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const base = process.env.TEST_URL || 'http://localhost:5173';
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
const errors = [];
page.on('pageerror', error => errors.push(error.message));
await page.addInitScript(() => {
  window.__draws = 0;
  const draw = WebGLRenderingContext.prototype.drawArrays;
  WebGLRenderingContext.prototype.drawArrays = function (...args) { window.__draws++; return draw.apply(this, args); };
});
try {
  await page.goto(base, { waitUntil: 'networkidle' });
  assert.equal(await page.locator('.ms-component-card').count(), componentCount);
  await page.getByRole('button', { name: 'WebGL 1', exact: true }).click();
  assert.equal(await page.locator('.ms-component-card').count(), 1);
  assert.ok((await page.locator('.ms-component-card').innerText()).includes('Eclipse'));
  await page.locator('.ms-component-card').click();
  await page.getByRole('heading', { name: 'Eclipse', exact: true }).waitFor();
  await page.frameLocator('iframe').locator('canvas.is-ready').waitFor();
  await page.getByRole('button', { name: 'Customize', exact: true }).click();
  await page.getByLabel(/Disc radius/).fill('0.25');
  await page.getByLabel(/Corona brightness/).fill('1.25');
  await page.getByRole('switch', { name: 'Pointer interaction', exact: true }).click();
  await page.getByRole('switch', { name: 'Show sample headline', exact: true }).click();
  await page.frameLocator('iframe').locator('.ms-eclipse-headline').waitFor();
  await page.getByRole('tab', { name: 'Usage', exact: true }).click();
  let text = await page.locator('#playground-panel pre').innerText();
  assert.ok(text.includes('radius={0.25}') && text.includes('intensity={1.25}') && text.includes('interactive={false}') && text.includes('<h1'));
  await page.getByRole('tab', { name: 'Component', exact: true }).click();
  assert.ok((await page.locator('#playground-panel pre').innerText()).includes('fragmentShader'));
  await page.locator('#playground-panel .ms-copy').click();
  await page.locator('#playground-panel').getByRole('button', { name: 'Copied', exact: true }).waitFor();
  await page.getByRole('tab', { name: 'CSS', exact: true }).click();
  assert.ok((await page.locator('#playground-panel pre').innerText()).includes('eclipse__fallback'));
  const download = page.waitForEvent('download');
  await page.getByRole('link', { name: 'Download files', exact: true }).click();
  assert.equal((await download).suggestedFilename(), 'eclipse.zip');
  await page.getByRole('button', { name: 'Reset', exact: true }).click();
  assert.equal(await page.getByRole('switch', { name: 'Pointer interaction', exact: true }).getAttribute('aria-checked'), 'true');
  await page.getByRole('tab', { name: 'Preview', exact: true }).click();
  await page.frameLocator('iframe').locator('canvas.is-ready').waitFor();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.waitForTimeout(300);
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  assert.ok((await page.locator('.ms-sidebar').boundingBox()).x < -200);
  await page.screenshot({ path: 'test-artifacts/eclipse/mobile-checked.png' });
  await page.goto(`${base}/preview/eclipse?embed=1`, { waitUntil: 'networkidle' });
  await page.locator('canvas.is-ready').waitFor();
  await page.waitForFunction(() => window.__draws > 3);
  await page.getByRole('button', { name: 'Pause eclipse', exact: true }).click();
  await page.getByRole('button', { name: 'Play eclipse', exact: true }).waitFor();
  await page.waitForTimeout(150);
  const pausedCount = await page.evaluate(() => window.__draws);
  await page.waitForTimeout(350);
  assert.equal(await page.evaluate(() => window.__draws), pausedCount);
  await page.getByRole('button', { name: 'Play eclipse', exact: true }).click();
  await page.waitForFunction(count => window.__draws > count + 2, pausedCount);
  await page.evaluate(() => {
    const gl = document.querySelector('canvas').getContext('webgl');
    window.__contextControl = gl.getExtension('WEBGL_lose_context');
    window.__contextControl.loseContext();
  });
  await page.waitForFunction(() => !document.querySelector('canvas').classList.contains('is-ready'));
  assert.ok((await page.locator('.eclipse__fallback').boundingBox()).width > 0);
  await page.evaluate(() => window.__contextControl.restoreContext());
  await page.locator('canvas.is-ready').waitFor();
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.reload({ waitUntil: 'networkidle' });
  await page.locator('canvas.is-ready').waitFor();
  const reducedCount = await page.evaluate(() => window.__draws);
  await page.waitForTimeout(400);
  assert.equal(await page.evaluate(() => window.__draws), reducedCount);
  assert.equal(await page.getByRole('button', { name: 'Pause eclipse', exact: true }).isDisabled(), true);
  const fallback = await browser.newPage({ viewport: { width: 390, height: 844 } });
  await fallback.addInitScript(() => {
    const getContext = HTMLCanvasElement.prototype.getContext;
    HTMLCanvasElement.prototype.getContext = function (type, ...args) {
      return type === 'webgl' ? null : getContext.call(this, type, ...args);
    };
  });
  await fallback.goto(`${base}/preview/eclipse`, { waitUntil: 'networkidle' });
  assert.equal(await fallback.locator('canvas.is-ready').count(), 0);
  assert.ok((await fallback.locator('.eclipse__fallback').boundingBox()).width > 100);
  await fallback.screenshot({ path: 'test-artifacts/eclipse/fallback-checked.png' });
  await fallback.close();
  assert.deepEqual(errors, []);
  console.log('PASS: Eclipse category, gallery, shader, controls, source tabs, clipboard, download, reset, mobile, pause/resume, context loss/restoration, reduced motion, and CSS fallback. No browser errors.');
} finally { await browser.close(); }
