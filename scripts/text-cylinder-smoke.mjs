import { chromium } from 'playwright';
import assert from 'node:assert/strict';
const browser = await chromium.launch();
const base = process.env.TEST_URL || 'http://localhost:5173';
const page = await browser.newPage({ viewport: { width: 1200, height: 850 } });
const errors = [];
page.on('pageerror', error => errors.push(error.message));
const rotation = async (row = 0) => Number((await page.locator('.text-cylinder__ring').nth(row).getAttribute('style')).match(/rotateY\(([-\d.]+)deg/)[1]);
const selected = async index => page.waitForFunction(index => document.querySelector('.text-cylinder').dataset.index === String(index), index);
try {
  await page.goto(`${base}/preview/text-cylinder?embed=1`, { waitUntil: 'networkidle' });
  const photo = page.locator('.text-cylinder__photo');
  const rect = await photo.boundingBox();
  assert.deepEqual(rect, { x: 468, y: 247.75, width: 264, height: 330 });
  const glyph = await page.locator('.text-cylinder__ring span').first().getAttribute('style');
  assert.ok(glyph.includes('rotateY(-10.4919deg)') && glyph.includes('translateZ(-554.296px)'));
  const first = await rotation();
  await page.waitForTimeout(1000);
  const second = await rotation();
  assert.ok(second - first > 16 && second - first < 21, 'rotation should advance about 18 degrees/second');
  assert.ok(Math.abs(second + await rotation(1) - 37) < 1, 'rings rotate in opposite directions');
  await page.getByRole('button', { name: 'Pause rotation', exact: true }).click();
  const paused = await rotation();
  await page.waitForTimeout(200);
  assert.equal(await rotation(), paused);
  await photo.click();
  await selected(1);
  await page.waitForTimeout(100);
  const interim = await page.locator('.text-cylinder__image.is-incoming').evaluate(el => ({ y: new DOMMatrix(getComputedStyle(el).transform).m42, h: el.clientHeight }));
  assert.ok(interim.y > 0 && interim.y < interim.h, 'incoming image should wipe upward');
  assert.equal(await page.locator('.text-cylinder__type').count(), 2);
  await page.waitForTimeout(800);
  assert.equal(await page.locator('.text-cylinder__image').count(), 1);
  assert.equal(await page.locator('.text-cylinder__type').count(), 1);
  assert.equal(await rotation(), paused, 'slide transition must preserve paused angle');
  await photo.focus();
  await page.keyboard.press('ArrowLeft'); await selected(0);
  await page.keyboard.press('ArrowLeft'); await selected(3);
  await page.keyboard.press('ArrowRight'); await selected(0);
  await page.keyboard.press('Enter'); await selected(1);
  await page.keyboard.press('Space'); await selected(2);
  for (let i = 0; i < 8; i++) await photo.click();
  await page.waitForTimeout(800);
  assert.equal(await page.locator('.text-cylinder__image').count(), 1);
  assert.equal(await page.locator('.text-cylinder__type').count(), 1);
  assert.equal(await page.locator('.text-cylinder__caption').innerText(), '03 / 04\nTOKYO');
  await page.getByRole('button', { name: 'Resume rotation', exact: true }).click();
  const resume = await rotation(); await page.waitForTimeout(200); assert.ok(await rotation() > resume);
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.reload({ waitUntil: 'networkidle' });
  const reduced = await rotation(); await page.waitForTimeout(200); assert.equal(await rotation(), reduced);
  await photo.click(); await selected(1);
  assert.equal(await page.locator('.text-cylinder__image').count(), 1);
  assert.equal(await page.locator('.text-cylinder__image').evaluate(el => el.getAnimations().length), 0);
  await page.emulateMedia({ reducedMotion: 'no-preference' });
  await page.goto(`${base}/preview/text-cylinder?embed=1&speed=-18`, { waitUntil: 'networkidle' });
  const backwards = await rotation(); await page.waitForTimeout(200); assert.ok(await rotation() < backwards);
  await page.goto(`${base}/components/text-cylinder`, { waitUntil: 'networkidle' });
  await page.getByRole('heading', { name: 'Text Cylinder', exact: true }).waitFor();
  await page.getByRole('button', { name: 'Customize', exact: true }).click();
  await page.getByLabel('First title', { exact: true }).fill('New horizons');
  await page.getByLabel('Rotation speed', { exact: true }).fill('12');
  await page.getByLabel('Panel theme', { exact: true }).selectOption('light');
  await page.getByRole('switch', { name: 'Pause rotation', exact: true }).click();
  await page.frameLocator('iframe').locator('.text-cylinder[data-theme=light][data-paused=true]').waitFor();
  await page.getByRole('tab', { name: 'Usage', exact: true }).click();
  const usage = await page.locator('#playground-panel pre').innerText();
  assert.ok(usage.includes('New horizons') && usage.includes('speed={12}') && usage.includes('paused={true}') && usage.includes('theme="light"'));
  await page.getByRole('tab', { name: 'Component', exact: true }).click();
  assert.ok((await page.locator('#playground-panel pre').innerText()).includes('function TextCylinder'));
  await page.locator('#playground-panel .ms-copy').click();
  await page.locator('#playground-panel').getByRole('button', { name: 'Copied', exact: true }).waitFor();
  await page.getByRole('tab', { name: 'CSS', exact: true }).click();
  assert.ok((await page.locator('#playground-panel pre').innerText()).includes('@keyframes tc-wipe'));
  const download = page.waitForEvent('download'); await page.getByRole('link', { name: 'Download files', exact: true }).click();
  assert.equal((await download).suggestedFilename(), 'text-cylinder.zip');
  await page.getByRole('button', { name: 'Reset', exact: true }).click();
  assert.equal(await page.getByLabel('First title', { exact: true }).inputValue(), 'Mount Fuji');
  await page.getByRole('tab', { name: 'Preview', exact: true }).click();
  await page.getByRole('button', { name: 'Mobile preview', exact: true }).click();
  await page.frameLocator('iframe').locator('.text-cylinder__photo').waitFor();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.waitForTimeout(400);
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  const touch = await browser.newPage({ viewport: { width: 390, height: 844 }, hasTouch: true, isMobile: true });
  await touch.goto(`${base}/preview/text-cylinder?embed=1`, { waitUntil: 'networkidle' });
  const mobilePhoto = touch.locator('.text-cylinder__photo');
  assert.ok(Math.abs((await mobilePhoto.boundingBox()).width - 179.4) < 0.1);
  await mobilePhoto.tap();
  await touch.waitForFunction(() => document.querySelector('.text-cylinder').dataset.index === '1');
  await touch.waitForTimeout(800);
  await touch.screenshot({ path: 'test-artifacts/text-cylinder/ours-mobile.png' });
  assert.equal(await touch.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await touch.close();
  const fallback = await browser.newPage();
  await fallback.route('**/radial-pop-out/fuji.webp', route => route.abort());
  await fallback.goto(`${base}/preview/text-cylinder?embed=1`, { waitUntil: 'networkidle' });
  await fallback.locator('.text-cylinder__fallback').waitFor();
  await fallback.locator('.text-cylinder__photo').click();
  await fallback.locator('.text-cylinder__fallback').waitFor({ state: 'hidden' });
  await fallback.close();
  assert.deepEqual(errors, []);
  console.log('PASS: Text Cylinder geometry, opposing rotation, pause/resume, image wipe, crossfade layers, wrapping/rapid navigation, keyboard, reduced motion, reversed speed, playground/source/copy/download, mobile/touch and failed-image recovery.');
} finally { await browser.close(); }
