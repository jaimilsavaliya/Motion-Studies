  await page.keyboard.press('ArrowRight'); await page.waitForTimeout(1000); assert.equal(await idx(), '0');
  const visible = await page.locator('.parallax-carousel__card').evaluateAll(els => els.filter(el => { const r=el.getBoundingClientRect(); return r.right>0 && r.left<innerWidth; }).map(el=>{const r=el.getBoundingClientRect(); return [r.left,r.right];}));
  assert.ok(visible[0][0] <= 12 && visible.at(-1)[1] >= 1188, 'wraparound must not expose an empty edge');
  await page.emulateMedia({reducedMotion:'reduce'}); await page.reload({waitUntil:'networkidle'});
  start = await x(); await page.waitForTimeout(300); assert.equal(await x(),start);
  assert.equal(await page.locator('.parallax-carousel__card').nth(7).locator('img').evaluate(el=>new DOMMatrix(getComputedStyle(el).transform).m41),0);
  await page.getByRole('button',{name:'Next image',exact:true}).click(); assert.notEqual(await x(),start);
  await page.emulateMedia({reducedMotion:'no-preference'});
