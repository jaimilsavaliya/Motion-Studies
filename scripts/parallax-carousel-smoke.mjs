  const rect = await page.locator('.parallax-carousel__card').nth(8).boundingBox();
  assert.ok(Math.abs(shift - Math.max(-60,Math.min(60,(rect.x+160-600)/600*60))) < .2);
  await page.mouse.down(); await page.mouse.move(220,425,{steps:20}); await page.mouse.up();
