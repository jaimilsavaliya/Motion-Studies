  await page.mouse.move(5,5); await page.waitForTimeout(500);
  start = await x(); await page.waitForTimeout(400); assert.ok(start - await x() > 10, 'leaving resumes autoplay');
  await page.getByRole('button',{name:'Pause autoplay',exact:true}).click(); await page.waitForTimeout(1500);
  start = await x(); await page.waitForTimeout(200); assert.ok(Math.abs(start - await x()) < .1);
  const viewport = page.locator('.parallax-carousel__viewport');
  await viewport.focus();
